test.describe('Panels', () => {
  test('T11: splitter, double-click maximise and restore, maximise button, Readable / Raw', async ({ page }) => {
    await setupDone(page)
    await page.goto(`/review/sample?${FAST}`)
    const h = async (p: string) => (await page.getByTestId(`panel-${p}`).boundingBox())!.height
    const before = await h('claude')
    const s = (await page.getByTestId('splitter').boundingBox())!
    await page.mouse.move(s.x + s.width / 2, s.y + s.height / 2)
    await page.mouse.down()
    await page.mouse.move(s.x + s.width / 2, s.y + 160, { steps: 6 })
    await page.mouse.up()
    expect(await h('claude')).toBeGreaterThan(before + 100)
    await page.getByTestId('panel-head-codex').dblclick()
    await expect(page.getByTestId('panels')).toHaveAttribute('data-max', 'codex')
    await expect(page.getByTestId('panel-claude')).toHaveCount(0)
    await page.getByTestId('panel-head-codex').dblclick()
    await expect(page.getByTestId('panel-claude')).toBeVisible()
    await page.getByTestId('max-claude').click()
    await expect(page.getByTestId('panel-codex')).toHaveCount(0)
    await page.getByTestId('max-claude').click()
    await expect(page.getByTestId('panel-codex')).toBeVisible()
    await page.getByTestId('mode-claude-raw').click()
    await expect(term(page, 'claude')).toContainText('"type":"result"')
    await expect(term(page, 'claude')).toContainText('claude -p --output-format stream-json')
    await page.getByTestId('mode-claude-readable').click()
    await expect(term(page, 'claude')).toContainText('Creating revision 3')
    // The panel area width is adjustable too.
    const area = async () => (await page.getByTestId('panels-area').boundingBox())!.width
    const w0 = await area()
    const ws = (await page.getByTestId('width-splitter').boundingBox())!
    await page.mouse.move(ws.x + ws.width / 2, ws.y + ws.height / 2)
    await page.mouse.down()
    await page.mouse.move(ws.x - 120, ws.y + ws.height / 2, { steps: 6 })
    await page.mouse.up()
    expect(await area()).toBeGreaterThan(w0 + 60)
  })
})

