test.describe('Robustness', () => {
  test.use({ allowConsoleErrors: true })
  test('a translated DOM never shows a raw crash: our screen or the next screen', async ({ page }) => {
    await setupDone(page)
    await page.goto(`/reviews?${FAST}`)
    await expect(page.locator('html')).toHaveAttribute('translate', 'no')
    await expect(page.locator('meta[name="google"]')).toHaveAttribute('content', 'notranslate')
    // What a page translator does: move every text node of the screen into a <font> wrapper.
    await page.evaluate(() => {
      const main = document.querySelector('[data-testid="main"]')!
      const walker = document.createTreeWalker(main, NodeFilter.SHOW_TEXT)
      const nodes: Text[] = []
      while (walker.nextNode()) nodes.push(walker.currentNode as Text)
      for (const n of nodes) {
        if (!n.textContent?.trim()) continue
        const outer = document.createElement('font'); const inner = document.createElement('font')
        inner.textContent = n.textContent; outer.appendChild(inner)
        n.parentNode!.replaceChild(outer, n)
      }
    })
    await page.getByTestId('nav-new').click()
    await expect(page.locator('[data-screen="S6"], [data-screen="error"]')).toBeVisible()
    await expect(page.getByText('Unexpected Application Error')).toHaveCount(0)
    if (await page.locator('[data-screen="error"]').count()) {
      await expect(page.getByTestId('error-reload')).toBeVisible()
      await page.getByTestId('error-back').click()
      await expect(page.locator('[data-screen="S11"]')).toBeVisible()
    }
  })
})
